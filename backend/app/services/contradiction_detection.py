"""Phase 3 feature C: contradiction detection over authorized case records.

Deterministic, subject-anchored comparison of structured claims across the
source records of one case, with a bounded local-LLM pass for semantic
statement comparison. Records are never compared merely for mentioning the
same entity: a pair is only evaluated when it shares an exact identifier
anchor (a transaction/reference id, or an entity identifier), and the field
rules below decide which comparisons are even meaningful for that anchor.

Design contract (``docs/ai/PHASE_3_DESIGN.md`` section 5):

- Comparison matrix (rule set v1.0.0; scope decides validity, preventing the
  obvious false positives):

  | class      | transaction-scoped fields | entity-scoped fields |
  |------------|---------------------------|----------------------|
  | amount     | transaction anchor only   | never compared       |
  | currency   | transaction anchor only   | never compared       |
  | date       | transaction anchor only   | never compared       |
  | status     | transaction anchor only   | either anchor        |
  | identifier | transaction anchor only   | either anchor        |

  Rationale: two transactions of one account legitimately differ in amount
  and date, so an entity anchor may only carry identifier/status claims -
  both records assert something about the *same subject* there.
- Originals are always preserved next to the normalized compared value;
  amounts compare as exact ``Decimal``, dates after deterministic parsing.
- Alternative explanations (timezone, document revision, transaction
  reversal, reporting window) are generated by transparent rules, not by the
  model. Missing information (e.g. absent time zones) is stated explicitly.
- The LLM may only compare two anchored statements and only ever yields a
  ``flagged``/``ai_unverified`` reviewable proposal - never a confirmation.
- Review states are records, never rewrites: ``confirmed``/``false_positive``
  come from the one-shot artifact review, while ``explained`` /
  ``requires_evidence`` / ``deferred`` are appended as child review
  artifacts. The candidate payload and the original evidence stay immutable.
"""

