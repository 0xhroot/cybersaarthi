_CURRENCY_SYMBOL_RE = re.compile(r"^[\u20b9$€£]\s*")
_NON_ALNUM_RE = re.compile(r"[^a-z0-9]+")
_TZ_HINT_RE = re.compile(r"[+-]\d{2}:?\d{2}|\bZ\b|UTC|GMT|IST|EST|PST|CET|IST\b", re.IGNORECASE)


def _field_norm(name: str) -> str:
    return _NON_ALNUM_RE.sub("_", name.strip().casefold()).strip("_")


def _hint_match(hints: tuple[str, ...], norm: str) -> bool:
    """Token-aware hint matching: ``state`` must not match ``statement``.

    Hints match whole underscore-separated tokens or contiguous token runs
    (``ref_no`` matches ``ref_no`` and ``txn_ref_no``), never substrings.
    """
    tokens = [token for token in norm.split("_") if token]
    for start in range(len(tokens)):
        for hint in hints:
            hint_tokens = hint.split("_")
            if tokens[start : start + len(hint_tokens)] == hint_tokens:
                return True
    return False


def _identifier_norm(value: str) -> str:
    """Identifier equality ignores case and punctuation (UTR-1 == UTR/1)."""
    return re.sub(r"[^a-z0-9]", "", value.casefold())


def _is_txn_scoped(field_norm: str) -> bool:
    return _hint_match(TXN_SCOPE_HINTS, field_norm)


