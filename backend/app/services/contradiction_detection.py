def _dates_agree(first: Claim, second: Claim) -> bool:
    """Two timestamps agree unless their UTC instants differ.

    When *either* side is date-granularity (no time was ever recorded), the
    comparison drops to day level: a date-only record can never contradict a
    time-of-day the source never stated.
    """
    a: datetime = first.compared
    b: datetime = second.compared
    if first.granularity == "date" or second.granularity == "date":
        return a.date() == b.date()
    return a == b


def compare_record_pair(
    record_a: RecordFacts,
    record_b: RecordFacts,
    claims_by_record: Mapping[str, Sequence[Claim]],
    *,
    anchor_value: str,
    anchor_scope: str,
    max_conflicts: int = MAX_CONFLICTS_PER_PAIR,
) -> list[Conflict]:
    """Apply the deterministic matrix to one anchored record pair."""
    claims_a = {claim.field_norm: claim for claim in claims_by_record[record_a.id]}
    claims_b = {claim.field_norm: claim for claim in claims_by_record[record_b.id]}
    anchor_fields = sorted(
        {
            claim.field
            for claims in (claims_by_record[record_a.id], claims_by_record[record_b.id])
            for claim in claims
            if claim.cls == "identifier" and claim.compared == anchor_value
        }
    )
    anchor = {
        "value": anchor_value,
        "scope": anchor_scope,
        "fields": ", ".join(anchor_fields) if anchor_fields else "",
    }
    conflicts: list[Conflict] = []
    currency_fields = {
        claim.field_norm
        for claim in (*claims_a.values(), *claims_b.values())
        if claim.cls == "currency"
    }
    for field_norm in sorted(set(claims_a) & set(claims_b)):
        if len(conflicts) >= max_conflicts:
            break
        first, second = claims_a[field_norm], claims_b[field_norm]
        if first.cls != second.cls:
            continue
        if first.cls == "identifier" and first.compared == second.compared:
            continue  # the shared anchor itself, or equal identifiers
        requires_txn_anchor = first.cls in ("amount", "currency", "date")
        if requires_txn_anchor and anchor_scope != "transaction":
            continue
        if first.txn_scoped and anchor_scope != "transaction":
            continue

        if first.cls == "amount":
            if first.compared == second.compared:
                continue
            category, rule = "amount", "contradiction.amount_disagreement"
            missing = () if currency_fields else ("currency code",)
        elif first.cls == "currency":
            if first.compared == second.compared:
                continue
            category, rule = "currency", "contradiction.currency_disagreement"
            missing = ()
        elif first.cls == "date":
            if _dates_agree(first, second):
                continue
            category, rule = "date", "contradiction.date_disagreement"
            both_naive = not _TZ_HINT_RE.search(first.original) and not _TZ_HINT_RE.search(
                second.original
            )
            missing = ("explicit time zone on both timestamps",) if both_naive else ()
        elif first.cls == "status":
            if first.compared == second.compared:
                continue
            category, rule = "status", "contradiction.status_disagreement"
            missing = ()
        else:
            if first.compared == second.compared:
                continue
            category, rule = "identifier", "contradiction.identifier_disagreement"
            missing = ()

        alternatives = list(_ALTERNATIVES[category])
        if category == "date" and missing:
            alternatives.insert(
                0,
                "timezone_difference: zone-less timestamps in different zones "
                "can describe the same instant",
            )
        explanation = (
            f"Both records reference {anchor_value} via {anchor['fields'] or 'an identifier'}, "
            f"but {first.field!r} differs: {first.original!r} vs {second.original!r}."
        )
        conflicts.append(
            Conflict(
                category=category,
                rule=rule,
                anchor=anchor,
                first=_side(first),
                second=_side(second),
                explanation=explanation[:1000],
                alternatives=tuple(alternatives),
                missing=missing,
            )
        )
    return conflicts


def generate_conflicts(
    records: Sequence[RecordFacts],
    *,
    max_records_per_anchor: int,
    max_pair_evals: int,
) -> tuple[list[tuple[Conflict, RecordFacts, RecordFacts]], dict[str, int]]:
    """Anchored pair generation + rule evaluation, bounded and deterministic."""
    counts: dict[str, int] = {
        "records_with_claims": 0,
        "anchor_groups": 0,
        "pair_evals": 0,
        "conflicts": 0,
        "conflicts_capped": 0,
    }
    by_id = {record.id: record for record in records}
    claims_by_record = {record.id: record_claims(record) for record in records}
    counts["records_with_claims"] = sum(1 for c in claims_by_record.values() if c)
    index = identifier_index(claims_by_record)

    out: list[tuple[Conflict, RecordFacts, RecordFacts]] = []
    seen: set[tuple[str, str, str]] = set()
    exhausted = False
    for value in sorted(index):
        if exhausted:
            break
        members = index[value]
        record_ids = sorted({record_id for record_id, _ in members})
        if len(record_ids) < 2:
            continue
        scope = anchor_scope(members)
        counts["anchor_groups"] += 1
        bounded_ids = record_ids[:max_records_per_anchor]
        for position, id_a in enumerate(bounded_ids):
            for id_b in bounded_ids[position + 1 :]:
                if counts["pair_evals"] >= max_pair_evals:
                    exhausted = True
                    break
                counts["pair_evals"] += 1
                for conflict in compare_record_pair(
                    by_id[id_a],
                    by_id[id_b],
                    claims_by_record,
                    anchor_value=value,
                    anchor_scope=scope,
                ):
                    key = (id_a, id_b, str(conflict.first.get("field") or ""))
                    if key in seen:
                        continue
                    seen.add(key)
                    if len(out) >= MAX_TOTAL_CONFLICTS:
                        counts["conflicts_capped"] += 1
                        continue
                    out.append((conflict, by_id[id_a], by_id[id_b]))
            if exhausted:
                break
    counts["conflicts"] = len(out)
    return out, counts


# -- semantic (LLM) statement comparison -------------------------------------------


@dataclass(frozen=True, slots=True)
class StatementFacts:
    record_id: str
    evidence_file_id: str
    record_no: int
    field: str
    field_norm: str
    index: int | None
    text: str


def collect_statements(
    records: Sequence[RecordFacts],
    extraction_artifacts: Sequence[DerivedArtifact],
) -> list[StatementFacts]:
    """Bounded statement excerpts per record (artifact claims + free text)."""
    statements: list[StatementFacts] = []
    for record in records:
        count = 0
        for name, value in record.raw_data.items():
            if count >= MAX_STATEMENTS_PER_RECORD:
                break
            if not isinstance(value, str) or len(value.strip()) < MIN_STATEMENT_CHARS:
                continue
            if classify_field(name, value) is not None:
                continue  # already covered by deterministic claim rules
            statements.append(
                StatementFacts(
                    record_id=record.id,
                    evidence_file_id=record.evidence_file_id,
                    record_no=record.record_no,
                    field=str(name),
                    field_norm=_field_norm(name),
                    index=None,
                    text=value.strip()[:MAX_STATEMENT_CHARS],
                )
            )
            count += 1

    record_by_id = {record.id: record for record in records}
    for artifact in extraction_artifacts:
        record_id = str(artifact.source_record_id) if artifact.source_record_id else None
        linked_record = record_by_id.get(record_id or "")
        if linked_record is None:
            continue
        fields = (artifact.payload or {}).get("fields")
        if not isinstance(fields, Mapping):
            continue
        raw_statements = fields.get("statements")
        if not isinstance(raw_statements, list):
            continue
        for index, value in enumerate(raw_statements):
            if index >= MAX_STATEMENTS_PER_RECORD:
                break
            if not isinstance(value, str) or len(value.strip()) < MIN_STATEMENT_CHARS:
                continue
            statements.append(
                StatementFacts(
                    record_id=linked_record.id,
                    evidence_file_id=linked_record.evidence_file_id,
                    record_no=linked_record.record_no,
                    field="statements",
                    field_norm="statements",
                    index=index,
                    text=value.strip()[:MAX_STATEMENT_CHARS],
                )
            )
    return statements


def semantic_pairs(
    records: Sequence[RecordFacts],
    statements: Sequence[StatementFacts],
    *,
    max_records_per_anchor: int,
    limit: int,
) -> list[tuple[str, StatementFacts, StatementFacts]]:
    """Anchored statement pairs eligible for model comparison, bounded."""
    by_record: dict[str, list[StatementFacts]] = {}
    for statement in statements:
        by_record.setdefault(statement.record_id, []).append(statement)
    claims_by_record = {
        record.id: record_claims(record) for record in records if record.id in by_record
    }
    index = identifier_index(claims_by_record)

    pairs: list[tuple[str, StatementFacts, StatementFacts]] = []
    seen: set[tuple[str, str, str]] = set()
    for value in sorted(index):
        if len(pairs) >= limit:
            break
        record_ids = sorted({record_id for record_id, _ in index[value] if record_id in by_record})
        if len(record_ids) < 2:
            continue
        bounded_ids = record_ids[:max_records_per_anchor]
        for position, id_a in enumerate(bounded_ids):
            for id_b in bounded_ids[position + 1 :]:
                if len(pairs) >= limit:
                    break
                for statement_a in sorted(
                    by_record[id_a], key=lambda s: (s.field_norm, s.index or 0)
                ):
                    match = next(
                        (
                            other
                            for other in by_record[id_b]
                            if other.field_norm == statement_a.field_norm
                            and normalize_text(other.text) != normalize_text(statement_a.text)
                        ),
                        None,
                    )
                    if match is None:
                        continue
                    key = (id_a, id_b, statement_a.field_norm)
                    if key in seen:
                        continue
                    seen.add(key)
                    pairs.append((value, statement_a, match))
                    break
    return pairs


class _StatementVerdictSchema(BaseModel):
    """Strict reply schema: extra keys (e.g. echoed ids) reject the reply."""

    contradicts: bool
    explanation: str = Field(min_length=1, max_length=600)


def parse_statement_verdict(text: str) -> dict[str, Any] | None:
    result = parse_structured(text, _StatementVerdictSchema)
    if result.data is None:
        return None
    return {
        "contradicts": bool(result.data["contradicts"]),
        "explanation": str(result.data["explanation"]).strip()[:300],
    }


class StatementComparer(Protocol):
    """The bounded model-call surface the runner needs (AIService implements it)."""

    async def compare_statements(self, *, first: str, second: str, anchor: str) -> Any: ...


def semantic_conflict(
    anchor_value: str,
    first: StatementFacts,
    second: StatementFacts,
    llm: dict[str, Any],
) -> Conflict:
    def side(statement: StatementFacts) -> dict[str, object]:
        return {
            "source_record_id": statement.record_id,
            "evidence_file_id": statement.evidence_file_id,
            "record_no": statement.record_no,
            "field": statement.field,
            "class": "statement",
            "value": statement.text[:300],
            "original": statement.text,
            "locator": (
                {
                    "record_no": statement.record_no,
                    "field": statement.field,
                    "index": statement.index,
                }
                if statement.index is not None
                else {"record_no": statement.record_no, "field": statement.field}
            ),
        }

    return Conflict(
        category="semantic",
        rule="contradiction.semantic_disagreement",
        anchor={"value": anchor_value, "scope": "entity", "fields": first.field},
        first=side(first),
        second=side(second),
        explanation=(
            f"Two {first.field!r} statements referencing {anchor_value} were compared by "
            "the local model, which judged them to disagree (unverified - review required)."
        ),
        alternatives=_ALTERNATIVES["semantic"],
        missing=(),
    )


# -- review lifecycle (child artifacts, never rewrites) -----------------------------


CONTRADICTION_STATES: tuple[Literal["explained", "requires_evidence", "deferred"], ...] = (
    "explained",
    "requires_evidence",
    "deferred",
)


class ContradictionRejected(ValueError):
    """Resolution refused; ``code`` carries the typed API error code."""

    def __init__(self, code: str, message: str) -> None:
        super().__init__(message)
        self.code = code


async def resolve_contradiction(
    session: AsyncSession,
    *,
    case_id: uuid.UUID,
    artifact_id: uuid.UUID,
    actor_id: uuid.UUID,
    state: str,
    note: str,
) -> DerivedArtifact:
    """Record a reviewer resolution state as an appended child artifact.

    ``explained`` / ``requires_evidence`` / ``deferred`` are new auditable
    records linked to the candidate (``parent_artifact_id``); the candidate
    payload, the original evidence and every earlier decision stay immutable.
    ``confirmed`` and ``false_positive`` remain the one-shot artifact review.
    """
    if state not in CONTRADICTION_STATES:
        raise ContradictionRejected(
            CODE_CONTRADICTION_STATE_INVALID,
            f"unknown contradiction state {state!r} "
            "(expected one of: " + ", ".join(CONTRADICTION_STATES) + ")",
        )
    if not note or not note.strip():
        raise ContradictionRejected(
            CODE_REVIEW_NOTE_REQUIRED, "a resolution note is required for every state"
        )
    parent = await artifacts_svc.get_artifact(session, case_id, artifact_id)
    if parent is None:
        raise ContradictionRejected(CODE_ARTIFACT_NOT_FOUND, f"artifact {artifact_id} not found")
    if parent.kind != "contradiction" or (parent.payload or {}).get("type") != "contradiction":
        raise ContradictionRejected(
            CODE_ARTIFACT_KIND_UNSUPPORTED, "artifact is not a contradiction candidate"
        )
    if parent.status != "pending_review":
        raise ContradictionRejected(
            CODE_ARTIFACT_NOT_REVIEWABLE,
            f"candidate is {parent.status}; only unresolved candidates accept resolution states",
        )
    if not await still_authorized_for_case(
        session, user_id=actor_id, case_id=case_id, permission=rbac.PERM_FINDINGS_REVIEW
    ):
        raise ContradictionRejected(
            CODE_CASE_ACCESS_DENIED,
            "review access to this case was revoked before the resolution could be recorded",
        )

    child, _ = await artifacts_svc.record_artifact(
        session,
        case_id=case_id,
        kind="contradiction",
        origin="deterministic",
        payload={
            "type": "contradiction_review",
            "state": state,
            "note": note.strip()[:2000],
            "for_artifact_id": str(parent.id),
        },
        evidence_file_id=(
            uuid.UUID(str(parent.evidence_file_id)) if parent.evidence_file_id else None
        ),
        source_record_id=(
            uuid.UUID(str(parent.source_record_id)) if parent.source_record_id else None
        ),
        source_locator=parent.source_locator,
        validation_status="valid",
        parser_version="contradiction_review:1.0.0",
        parent_artifact_id=parent.id,
        created_by=actor_id,
        status="recorded",
    )
    await session.flush()
    return child


# -- execution (bounded job runner) ----------------------------------------------------


async def _load_records(
    session: AsyncSession, case_id: uuid.UUID, cap: int
) -> tuple[list[RecordFacts], bool]:
    result = await session.execute(
        select(SourceRecord)
        .join(EvidenceFile, SourceRecord.evidence_file_id == EvidenceFile.id)
        .where(
            EvidenceFile.case_id == str(case_id),
            EvidenceFile.deleted_at.is_(None),
        )
        .order_by(EvidenceFile.created_at, EvidenceFile.id, SourceRecord.record_no)
        .limit(cap + 1)
    )
    rows = list(result.scalars())
    bounded = len(rows) > cap
    facts = [
        RecordFacts(
            id=str(record.id),
            evidence_file_id=str(record.evidence_file_id),
            record_no=record.record_no,
            raw_data=dict(record.raw_data),
        )
        for record in rows[:cap]
    ]
    return facts, bounded


async def _load_extraction_artifacts(
    session: AsyncSession, case_id: uuid.UUID, cap: int
) -> list[DerivedArtifact]:
    result = await session.execute(
        select(DerivedArtifact)
        .where(
            DerivedArtifact.case_id == str(case_id),
            DerivedArtifact.kind == "extraction",
            DerivedArtifact.status.in_(("pending_review", "approved")),
        )
        .order_by(DerivedArtifact.created_at, DerivedArtifact.id)
        .limit(cap)
    )
    return list(result.scalars())


async def execute_contradiction_detection(
    session: AsyncSession,
    *,
    job_id: uuid.UUID,
    settings: Settings,
    comparer: StatementComparer | None = None,
) -> None:
    """Run one pending contradiction-detection job to a terminal state.

    Candidates are never a job failure. Only authorization loss or unexpected
    crashes fail the job - always with a typed code.
    """
    job = await session.get(AnalysisJob, job_id)
    if job is None or job.status != "pending":
        return
    case_id = uuid.UUID(str(job.case_id))
    actor_id = uuid.UUID(str(job.actor_id)) if job.actor_id else None

    if actor_id is None:
        await _fail_job(
            session, job, code="CONTRADICTION_FAILED", error="job has no actor reference"
        )
        return
    if not await still_authorized_for_case(
        session, user_id=actor_id, case_id=case_id, permission=rbac.PERM_EVIDENCE_READ
    ):
        await _fail_job(
            session,
            job,
            code=CODE_CASE_ACCESS_DENIED,
            error="access to this case was revoked before detection ran",
            denial=True,
        )
        return
    if job.cancel_requested:
        await _stop_job(session, job, stop="cancel", summary={}, case_id=case_id, actor_id=actor_id)
        return

    jobs_svc.transition(job, "running")
    await session.commit()

    summary: dict[str, Any] = {
        "records_scanned": 0,
        "records_bounded": False,
        "records_with_claims": 0,
        "anchor_groups": 0,
        "pair_evals": 0,
        "conflicts": 0,
        "artifacts_created": 0,
        "artifacts_reused": 0,
        "semantic_pairs": 0,
        "semantic_llm": 0,
        "semantic_invalid": 0,
        "semantic_skipped": 0,
    }
    stage = "load"
    try:
        records, bounded = await _load_records(session, case_id, settings.CONTRADICTION_MAX_RECORDS)
        summary["records_scanned"] = len(records)
        summary["records_bounded"] = bounded

        stage = "compare"
        conflicts, counts = generate_conflicts(
            records,
            max_records_per_anchor=settings.CONTRADICTION_MAX_RECORDS_PER_ANCHOR,
            max_pair_evals=settings.CONTRADICTION_MAX_PAIR_EVALS,
        )
        summary.update(counts)
        await session.refresh(job)
        stop = jobs_svc.should_stop(job)
        if stop is not None:
            await _stop_job(
                session, job, stop=stop, summary=summary, case_id=case_id, actor_id=actor_id
            )
            return

        stage = "record"
        jobs_svc.advance(job, processed=0, total=len(conflicts))
        await session.commit()
        for index, (conflict, first, _) in enumerate(conflicts, start=1):
            await session.refresh(job)
            stop = jobs_svc.should_stop(job)
            if stop is not None:
                await _stop_job(
                    session,
                    job,
                    stop=stop,
                    summary=summary,
                    case_id=case_id,
                    actor_id=actor_id,
                )
                return
            if not await still_authorized_for_case(
                session, user_id=actor_id, case_id=case_id, permission=rbac.PERM_EVIDENCE_READ
            ):
                await _fail_job(
                    session,
                    job,
                    code=CODE_CASE_ACCESS_DENIED,
                    error="access to this case was revoked mid-run; detection stopped",
                    denial=True,
                    summary=summary,
                )
                return
            created = await _record_candidate(
                session,
                job=job,
                actor_id=actor_id,
                conflict=conflict,
                source_record_id=uuid.UUID(first.id),
                evidence_file_id=uuid.UUID(first.evidence_file_id),
                origin="deterministic",
            )
            summary["artifacts_created" if created else "artifacts_reused"] += 1
            jobs_svc.advance(job, processed=index, total=len(conflicts))
            await session.commit()

        # Bounded semantic pass: anchored statement pairs only.
        stage = "semantic"
        if comparer is not None and settings.AI_FEATURE_CONTRADICTION:
            artifacts = await _load_extraction_artifacts(
                session, case_id, settings.CONTRADICTION_MAX_RECORDS
            )
            statements = collect_statements(records, artifacts)
            pairs = semantic_pairs(
                records,
                statements,
                max_records_per_anchor=settings.CONTRADICTION_MAX_RECORDS_PER_ANCHOR,
                limit=settings.CONTRADICTION_MAX_LLM_PAIRS,
            )
            summary["semantic_pairs"] = len(pairs)
            for anchor_value, stmt_first, stmt_second in pairs:
                await session.refresh(job)
                if jobs_svc.should_stop(job) is not None:
                    break
                verdict = await _compare_with_model(
                    comparer, anchor_value, stmt_first, stmt_second, summary
                )
                if verdict is None or not verdict["contradicts"]:
                    continue
                conflict = semantic_conflict(anchor_value, stmt_first, stmt_second, verdict)
                created = await _record_candidate(
                    session,
                    job=job,
                    actor_id=actor_id,
                    conflict=conflict,
                    source_record_id=uuid.UUID(stmt_first.record_id),
                    evidence_file_id=uuid.UUID(stmt_first.evidence_file_id),
                    origin="llm",
                    llm=verdict,
                )
                summary["artifacts_created" if created else "artifacts_reused"] += 1
                await session.commit()

        job.result_summary = summary
        jobs_svc.transition(job, "succeeded")
        await session.flush()
        await audit_svc.record_audit(
            session,
            actor_id=actor_id,
            action="contradiction.completed",
            resource_type="analysis_job",
            resource_id=job.id,
            case_id=case_id,
            metadata={
                "conflicts": summary["conflicts"],
                "artifacts_created": summary["artifacts_created"],
                "semantic_pairs": summary["semantic_pairs"],
            },
        )
        await session.commit()
    except Exception:
        logger.exception("contradiction detection crashed", extra={"job_id": str(job.id)})
        await session.rollback()
        await session.refresh(job)
        await _fail_job(
            session,
            job,
            code="CONTRADICTION_FAILED",
            error=f"unexpected error during stage {stage}",
            summary=summary,
        )


async def _record_candidate(
    session: AsyncSession,
    *,
    job: AnalysisJob,
    actor_id: uuid.UUID,
    conflict: Conflict,
    source_record_id: uuid.UUID,
    evidence_file_id: uuid.UUID,
    origin: str,
    llm: dict[str, Any] | None = None,
) -> bool:
    """Persist one contradiction candidate (content-addressed: identical
    facts dedupe onto the existing artifact)."""
    payload = conflict.as_payload(llm=llm)
    locator = conflict.first.get("locator")
    artifact, created = await artifacts_svc.record_artifact(
        session,
        case_id=uuid.UUID(str(job.case_id)),
        kind="contradiction",
        origin=origin,
        payload=payload,
        source_record_id=source_record_id,
        evidence_file_id=evidence_file_id,
        source_locator=locator if isinstance(locator, dict) else None,
        validation_status="flagged" if origin == "llm" else "valid",
        validation_errors=(
            [
                {
                    "field": "llm_verdict",
                    "code": "ai_unverified",
                    "message": (
                        "the local model judged these statements to contradict; "
                        "the verdict is unverified and never confirms a discrepancy"
                    ),
                }
            ]
            if origin == "llm"
            else None
        ),
        parser_version=f"contradiction_rules:{CONTRADICTION_RULES_VERSION}",
        prompt_version=CONTRADICTION_PROMPT_VERSION if origin == "llm" else None,
        model_profile="contradiction" if origin == "llm" else None,
        analysis_job_id=job.id,
        created_by=actor_id,
        status="pending_review",
    )
    _ = artifact
    return created


async def _compare_with_model(
    comparer: StatementComparer,
    anchor_value: str,
    first: StatementFacts,
    second: StatementFacts,
    summary: dict[str, Any],
) -> dict[str, Any] | None:
    try:
        completion = await comparer.compare_statements(
            first=first.text, second=second.text, anchor=anchor_value
        )
    except Exception:
        logger.warning("statement comparison failed; skipping candidate")
        summary["semantic_skipped"] += 1
        return None
    verdict = parse_statement_verdict(getattr(completion, "text", "") or "")
    if verdict is None:
        summary["semantic_invalid"] += 1
        return None
    if not verdict["contradicts"]:
        summary["semantic_skipped"] += 1
        return None
    summary["semantic_llm"] += 1
    return verdict


async def _stop_job(
    session: AsyncSession,
    job: AnalysisJob,
    *,
    stop: str,
    summary: dict[str, Any],
    case_id: uuid.UUID,
    actor_id: uuid.UUID,
) -> None:
    if summary:
        job.result_summary = summary
    if stop == "cancel":
        jobs_svc.transition(job, "canceled")
        action = "contradiction.canceled"
    else:
        job.error = f"contradiction detection timed out after {job.timeout_seconds}s"
        jobs_svc.transition(job, "failed")
        action = "contradiction.timed_out"
    await session.flush()
    await audit_svc.record_audit(
        session,
        actor_id=actor_id,
        action=action,
        resource_type="analysis_job",
        resource_id=job.id,
        case_id=case_id,
        metadata={"conflicts": summary.get("conflicts", 0)} if summary else {},
    )
    await session.commit()


async def _fail_job(
    session: AsyncSession,
    job: AnalysisJob,
    *,
    code: str,
    error: str,
    summary: dict[str, Any] | None = None,
    denial: bool = False,
    stage: str = "authorize",
) -> None:
    if jobs_svc.is_terminal(job.status):
        return
    payload: dict[str, Any] = dict(summary) if summary else {}
    payload["error_code"] = code
    job.result_summary = payload
    job.error = error[:500]
    jobs_svc.transition(job, "failed")
    await session.flush()
    case_id = uuid.UUID(str(job.case_id))
    actor_id = uuid.UUID(str(job.actor_id)) if job.actor_id else None
    await audit_svc.record_audit(
        session,
        actor_id=actor_id,
        action="contradiction.denied" if denial else "contradiction.failed",
        resource_type="analysis_job",
        resource_id=job.id,
        case_id=case_id,
        metadata={"code": code, "stage": stage},
    )
    await session.commit()


async def run_contradiction_job(app: FastAPI, job_id: uuid.UUID) -> None:
    """Background worker: own DB session, own scope, never raises."""
    from app.core.config import get_settings
    from app.db.postgres import Database

    settings: Settings = get_settings()
    database: Database = app.state.database
    factory: async_sessionmaker[AsyncSession] = database.session_factory()
    comparer: StatementComparer | None = getattr(app.state, "ai_service", None)
    try:
        async with factory() as session:
            await execute_contradiction_detection(
                session, job_id=job_id, settings=settings, comparer=comparer
            )
    except Exception:  # session-level crash: fail the job best-effort
        logger.exception("background contradiction detection failed", extra={"job_id": str(job_id)})
        async with factory() as session:
            job = await session.get(AnalysisJob, job_id)
            if job is not None and not jobs_svc.is_terminal(job.status):
                await _fail_job(
                    session,
                    job,
                    code="CONTRADICTION_FAILED",
                    error="background contradiction detection task crashed",
                )
